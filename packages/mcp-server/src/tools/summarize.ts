import { z } from 'zod';
import { db, tasks, projects } from '@trackmate/database';
import { eq, ne } from 'drizzle-orm';
import type { McpToolResult, McpToolDefinition } from '@trackmate/shared';

// ─────────────────────────────────────────────────────────────────────────────
// Schema
// ─────────────────────────────────────────────────────────────────────────────

const SummarizeSchema = z.object({
  projectId: z.string().min(1),
});

// ─────────────────────────────────────────────────────────────────────────────
// Tool: summarize_project
// ─────────────────────────────────────────────────────────────────────────────

export async function summarize_project(args: Record<string, unknown>): Promise<McpToolResult> {
  const parsed = SummarizeSchema.safeParse(args);
  if (!parsed.success) {
    return { content: [{ type: 'text', text: `Error: ${parsed.error.message}` }], isError: true };
  }

  const [project] = await db
    .select()
    .from(projects)
    .where(eq(projects.id, parsed.data.projectId))
    .limit(1);

  if (!project) {
    return { content: [{ type: 'text', text: `Error: Project not found` }], isError: true };
  }

  const allTasks = await db
    .select()
    .from(tasks)
    .where(eq(tasks.projectId, parsed.data.projectId));

  const today = new Date().toISOString().split('T')[0]!;

  const done       = allTasks.filter(t => t.status === 'done').length;
  const inProgress = allTasks.filter(t => t.status === 'in_progress').length;
  const blocked    = allTasks.filter(t => t.status === 'blocked');
  const todo       = allTasks.filter(t => t.status === 'todo').length;
  const overdue    = allTasks.filter(t => t.dueDate && t.dueDate < today && t.status !== 'done');
  const pct        = allTasks.length > 0 ? Math.round((done / allTasks.length) * 100) : 0;

  // Build a human-readable narrative summary
  const lines: string[] = [
    `📊 **${project.name}** — Project Summary`,
    `Status: ${project.status.replace('_', ' ').toUpperCase()}`,
    ``,
    `**Progress: ${pct}% complete** (${done}/${allTasks.length} tasks done)`,
    ``,
    `Task breakdown:`,
    `  ✅ Done:        ${done}`,
    `  🔄 In Progress: ${inProgress}`,
    `  📋 Todo:        ${todo}`,
    `  🚫 Blocked:     ${blocked.length}`,
    `  ⚠️  Overdue:     ${overdue.length}`,
  ];

  if (blocked.length > 0) {
    lines.push(``, `**Blockers requiring attention:**`);
    blocked.forEach(t => lines.push(`  • ${t.title}`));
  }

  if (overdue.length > 0) {
    lines.push(``, `**Overdue tasks:**`);
    overdue.forEach(t => {
      const days = t.dueDate
        ? Math.ceil((Date.now() - new Date(t.dueDate).getTime()) / 86_400_000)
        : 0;
      lines.push(`  • ${t.title} (${days}d overdue, ${t.priority} priority)`);
    });
  }

  if (project.githubRepo) {
    lines.push(``, `🔗 GitHub: https://github.com/${project.githubRepo}`);
  }

  lines.push(``, `_Generated by TrackMate AI — ${new Date().toLocaleString()}_`);

  return { content: [{ type: 'text', text: lines.join('\n') }] };
}

export const summarize_project_definition: McpToolDefinition = {
  name: 'summarize_project',
  description: 'Generate a human-readable summary of project status including progress, blockers, and overdue tasks.',
  inputSchema: {
    type: 'object',
    required: ['projectId'],
    properties: {
      projectId: { type: 'string', description: 'Project ID to summarize' },
    },
  },
};
